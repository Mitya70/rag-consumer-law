# Контрольный вариант без поиска: модель отвечает только по собственным знаниям, без фрагментов документов.
NOCONTEXT_SYSTEM = "Ты помощник по вопросам защиты прав потребителей в России. Ответь на вопрос пользователя."
NOCONTEXT_USER = "Вопрос: {question}\nОтвет:"

USER_TEMPLATE = "Фрагменты документов:\n{contexts}\n\nВопрос: {question}\nОтвет:"


def build_messages(variant: str, contexts: str, question: str) -> list[dict]:
    if variant == "no_context":
        return [{"role": "system", "content": NOCONTEXT_SYSTEM}, {"role": "user", "content": NOCONTEXT_USER.format(question=question)}]
    if variant == "naive":
        return [{"role": "system", "content": NAIVE_SYSTEM}, {"role": "user", "content": USER_TEMPLATE.format(contexts=contexts, question=question)}]
    messages = [{"role": "system", "content": STRICT_SYSTEM}]
    if variant == "strict_fewshot":
        for ex in FEWSHOT_EXAMPLES:
            messages.append({"role": "user", "content": USER_TEMPLATE.format(contexts=ex["contexts"], question=ex["question"])})
            messages.append({"role": "assistant", "content": ex["answer"]})
    elif variant != "strict":
        raise ValueError(variant)
    messages.append({"role": "user", "content": USER_TEMPLATE.format(contexts=contexts, question=question)})
    return messages


